const DEFAULT_MODELS = ["google/gemma-4-31b-it:free", "google/gemma-4-26b-a4b-it:free", "nvidia/nemotron-3.5-lightning:free"]
function modelList() {
  const env = (process.env.OPENROUTER_MODEL || "").split(",").map((m) => m.trim()).filter(Boolean)
  return env.length ? env : DEFAULT_MODELS
}

async function callModel(system, messages, models) {
  const key = process.env.OPENROUTER_API_KEY
  if (!key) {
    console.error("OPENROUTER_API_KEY не задан")
    return { ok: false, retry: false }
  }
  const controller = new AbortController()
  const timer = setTimeout(() => controller.abort(), 20000)
  try {
    const res = await fetch("https://openrouter.ai/api/v1/chat/completions", {
      method: "POST",
      signal: controller.signal,
      headers: { Authorization: `Bearer ${key}`, "Content-Type": "application/json", "X-Title": "Psy demo assistants" },
      body: JSON.stringify({
        ...(models.length === 1 ? { model: models[0] } : { models: models.slice(0, 3) }),
        messages: [{ role: "system", content: system }, ...messages],
        max_tokens: 2000,
        temperature: 0.5,
        reasoning: { effort: "low", exclude: true },
        ...(models[0].endsWith(":free") ? {} : { provider: { data_collection: "deny" } }),
      }),
    })
    if (!res.ok) {
      console.error("OpenRouter:", res.status, (await res.text().catch(() => "")).slice(0, 300))
      return { ok: false, retry: res.status >= 500 || res.status === 429 || res.status === 402 }
    }
    const data = await res.json()
    const choice = data?.choices?.[0]
    const text = typeof choice?.message?.content === "string" ? choice.message.content.trim() : ""
    if (!text || choice?.finish_reason === "length") {
      console.warn("OpenRouter: пустой или оборванный ответ", data?.model, choice?.finish_reason)
      return { ok: false, retry: true }
    }
    return { ok: true, text }
  } catch (err) {
    console.error("OpenRouter error:", err?.message || err)
    return { ok: false, retry: true }
  } finally {
    clearTimeout(timer)
  }
}

export async function askModel(system, messages) {
  const models = modelList()
  const attempts = models.length > 1 ? [models, [...models.slice(1), models[0]]] : [models, models]
  for (const list of attempts) {
    const r = await callModel(system, messages, list)
    if (r.ok) return r.text
    if (!r.retry) return null
  }
  return null
}
