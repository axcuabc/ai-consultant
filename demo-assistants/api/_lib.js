const DEFAULT_HOSTS = "write-silent-endive.tilda.ws,tilda.cc,localhost,127.0.0.1"
export function originAllowed(origin) {
  if (!origin) return false
  let host
  try {
    host = new URL(origin).hostname.toLowerCase()
  } catch {
    return false
  }
  const allowed = (process.env.ALLOWED_HOSTS || DEFAULT_HOSTS).split(",").map((h) => h.trim().toLowerCase()).filter(Boolean)
  return allowed.some((a) => host === a || host.endsWith("." + a))
}

export function cors(req, res) {
  res.setHeader("Access-Control-Allow-Origin", req.headers.origin || "*")
  res.setHeader("Vary", "Origin")
  res.setHeader("Access-Control-Allow-Methods", "GET, POST, OPTIONS")
  res.setHeader("Access-Control-Allow-Headers", "Content-Type")
  res.setHeader("Access-Control-Max-Age", "86400")
}

// ——— Ограничение частоты (в памяти экземпляра функции — защита от простого спама) ———
const hits = new Map()
export function rateLimited(key, limit, windowMs) {
  const now = Date.now()
  const recent = (hits.get(key) || []).filter((t) => now - t < windowMs)
  recent.push(now)
  hits.set(key, recent)
  if (hits.size > 5000) for (const [k, v] of hits) if (!v.some((t) => now - t < windowMs)) hits.delete(k)
  return recent.length > limit
}

