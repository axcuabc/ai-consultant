// Сообщения об угрозе жизни не отдаём нейросети: она может промолчать,
// ответить шаблоном «свяжитесь с нами» или придумать несуществующий номер.
// Вместо этого сразу отвечаем проверенным текстом с телефонами помощи.

const PATTERNS: RegExp[] = [
  /не\s+хочу\s+(больше\s+)?жить(?!\s+(с|со|в|во|у|вместе|там|здесь|тут|одн|рядом|под|на))/,
  /жить\s+не\s+хочу/,
  /не\s+хочется\s+жить(?!\s+(с|со|в|во|у|вместе|там|здесь|тут|одн|рядом|под|на))/,
  /жить\s+не\s+хочется/,
  /хочу\s+умереть/,
  /хочется\s+умереть/,
  /покончить\s+с\s+(собой|жизнью)/,
  /поконч(у|ить)\s+с\s+собой/,
  /убить\s+себя/,
  /убью\s+себя/,
  /суицид/,
  /самоубийств/,
  /свести\s+сч[её]ты\s+с\s+жизнью/,
  /наложить\s+на\s+себя\s+руки/,
  /вскрыть\s+вены/,
  /вскрою\s+вены/,
  /(режу|порезать|резать)\s+себя/,
  /причинить\s+себе\s+вред/,
  /лучше\s+бы\s+меня\s+не\s+было/,
  /не\s+вижу\s+смысла\s+жить/,
]

export const CRISIS_REPLY = [
  "Мне очень жаль, что вам сейчас так тяжело. Вы не одни, и помощь есть прямо сейчас.",
  "",
  "Если есть угроза жизни — звоните 112.",
  "Поговорить с психологом бесплатно: 8-800-775-17-17 (центр экстренной психологической помощи МЧС России).",
  "Детям, подросткам и родителям: 8-800-2000-122 (бесплатно).",
  "",
  "Я автоматический помощник и не могу заменить живого человека. Пожалуйста, позвоните сейчас или напишите тому, кому доверяете.",
].join("\n")

/** Если последнее сообщение посетителя похоже на угрозу жизни — готовый ответ, иначе null. */
export function crisisReply(lastUserMessage: string): string | null {
  const text = lastUserMessage.toLowerCase().replace(/ё/g, "е")
  return PATTERNS.some((p) => p.test(text.replace(/ё/g, "е"))) ? CRISIS_REPLY : null
}
